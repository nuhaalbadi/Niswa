"""Count and collect tweets used to construct the benchmark dataset.

REQUIREMENTS
------------
1. Python 3 and Tweepy (install with: pip install tweepy).
2. Twitter API access that supports full-archive count and search endpoints.
3. A bearer token stored in the TWITTER_BEARER_TOKEN environment variable.

ARGUMENTS
---------
mode
    Required positional argument. Use ``count`` to calculate tweet volumes
    before collection or ``collect`` to retrieve tweets.
--output-dir PATH
    Required directory in which the generated CSV files will be stored.
--query TEXT
    Optional Twitter API query. If omitted, the study query defined by
    DEFAULT_QUERY is used. 
--counts PATH
    Path to ``pre_daily_count.csv`` generated by count mode. This argument is
    required only when mode is ``collect``.
--threshold INTEGER
    Daily-volume threshold used to select the retrieval window. The default is
    6,000 tweets. Days at or below the threshold use a full-day window; days
    above it use a randomly selected eight-hour window.
--page-limit INTEGER
    Maximum API pages requested for each retrieval window. The default is 3;
    with 500 tweets per page, this limits retrieval to 1,500 tweets per window.

HOW TO RUN
----------
First, provide the bearer token without placing it in this source file:

    export TWITTER_BEARER_TOKEN="your_bearer_token"

Stage 1: count matching tweets for every day and study period:

    python collect_tweets.py count \
        --output-dir output

This creates ``pre_daily_count.csv`` and ``pre_period_count.csv``.

Stage 2: collect tweets using the daily counts created in Stage 1:

    python collect_tweets.py collect \
        --counts output/pre_daily_count.csv \
        --output-dir output

This creates one tweet CSV per period, plus ``daily_count.csv`` and
``period_count.csv``. 
"""

import argparse
import csv
import os
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

import tweepy


DATE_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
DEFAULT_QUERY = (
    "(الحرمه OR المراه OR البنت OR الحريم OR النساء OR البنات) "
    "-is:retweet lang:ar"
)
PERIOD_TIMESTAMPS = [
    ("2011-01-10T00:00:00Z", "2013-01-11T00:00:00Z"),
    ("2013-01-11T00:00:00Z", "2015-08-30T00:00:00Z"),
    ("2015-08-30T00:00:00Z", "2017-09-26T00:00:00Z"),
    ("2017-09-26T00:00:00Z", "2019-08-01T00:00:00Z"),
    ("2019-08-01T00:00:00Z", "2021-07-31T00:00:00Z"),
]


def parse_timestamp(value):
    """Parse an ISO 8601 UTC timestamp used by the Twitter API."""
    return datetime.strptime(value, DATE_FORMAT).replace(tzinfo=timezone.utc)


def format_timestamp(value):
    """Format a datetime as an ISO 8601 UTC timestamp."""
    return value.astimezone(timezone.utc).strftime(DATE_FORMAT)


def create_client():
    """Create an authenticated Twitter API v2 client."""
    bearer_token = os.environ.get("TWITTER_BEARER_TOKEN")
    if not bearer_token:
        raise RuntimeError(
            "Set the TWITTER_BEARER_TOKEN environment variable before running."
        )
    return tweepy.Client(bearer_token=bearer_token, wait_on_rate_limit=True)


def count_tweets(client, query, periods, output_dir):
    """Count matching tweets for every day and study period."""
    daily_path = output_dir / "pre_daily_count.csv"
    period_path = output_dir / "pre_period_count.csv"

    with daily_path.open("w", newline="", encoding="utf-8") as daily_file, \
            period_path.open("w", newline="", encoding="utf-8") as period_file:
        daily_writer = csv.writer(daily_file)
        period_writer = csv.writer(period_file)
        daily_writer.writerow(["day_start", "day_end", "tweet_count"])
        period_writer.writerow(["period_start", "period_end", "tweet_count"])

        # Count tweets for each day.
        for period_start, period_end in periods:
            period_total = 0
            current_day = period_start

            while current_day < period_end:
                next_day = min(current_day + timedelta(days=1), period_end)
                response = client.get_all_tweets_count(
                    query=query,
                    start_time=current_day,
                    end_time=next_day,
                    granularity="day",
                )
                day_total = sum(item["tweet_count"] for item in (response.data or []))
                daily_writer.writerow(
                    [format_timestamp(current_day), format_timestamp(next_day), day_total]
                )
                period_total += day_total
                current_day = next_day

            period_writer.writerow(
                [format_timestamp(period_start), format_timestamp(period_end), period_total]
            )


def read_daily_counts(counts_path):
    """Load daily tweet volumes keyed by the start timestamp."""
    with counts_path.open(newline="", encoding="utf-8") as file:
        return {
            row["day_start"]: int(row["tweet_count"])
            for row in csv.DictReader(file)
        }


def choose_window(day_start, tweet_count, threshold):
    """Choose the full day or a random eight-hour window."""
    if tweet_count <= threshold:
        return day_start, day_start + timedelta(days=1)

    start_hour = random.randint(0, 16)
    window_start = day_start.replace(hour=start_hour)
    return window_start, window_start + timedelta(hours=8)


def tweet_record(tweet, user, index):
    """Convert a tweet and its author metadata to one output row."""
    metrics = tweet.public_metrics
    user_metrics = user.public_metrics
    return {
        "index": index,
        "tweet_id": tweet.id,
        "tweet_text": tweet.text.strip(),
        "tweet_created_at": format_timestamp(tweet.created_at),
        "tweet_source": tweet.source,
        "tweet_lang": tweet.lang,
        "retweet_count": metrics["retweet_count"],
        "reply_count": metrics["reply_count"],
        "like_count": metrics["like_count"],
        "quote_count": metrics["quote_count"],
        "in_reply_to_user_id": tweet.in_reply_to_user_id,
        "user_id": tweet.author_id,
        "screen_name": user.name,
        "username": user.username,
        "profile_created_at": format_timestamp(user.created_at),
        "profile_description": (user.description or "").strip(),
        "profile_location": user.location,
        "followers_count": user_metrics["followers_count"],
        "following_count": user_metrics["following_count"],
        "tweet_count": user_metrics["tweet_count"],
        "profile_image_url": user.profile_image_url,
    }


def collect_tweets(
    client, query, periods, daily_counts, output_dir, threshold, page_limit
):
    """Collect the study sample and write tweet and collection-count files."""
    daily_path = output_dir / "daily_count.csv"
    period_path = output_dir / "period_count.csv"

    with daily_path.open("w", newline="", encoding="utf-8") as daily_file, \
            period_path.open("w", newline="", encoding="utf-8") as period_file:
        daily_writer = csv.writer(daily_file)
        period_writer = csv.writer(period_file)
        daily_writer.writerow(["day_start", "day_end", "tweet_count"])
        period_writer.writerow(["period_start", "period_end", "tweet_count"])

        for period_number, (period_start, period_end) in enumerate(periods, start=1):
            tweets_path = output_dir / f"tweets_period_{period_number}.csv"
            period_total = 0

            with tweets_path.open("w", newline="", encoding="utf-8") as tweets_file:
                tweets_writer = None
                current_day = period_start

                while current_day < period_end:
                    count_key = format_timestamp(current_day)
                    window_start, window_end = choose_window(
                        current_day, daily_counts[count_key], threshold
                    )
                    day_total = 0

                    # Request up to three pages of 500 tweets per window.
                    paginator = tweepy.Paginator(
                        client.search_all_tweets,
                        query=query,
                        start_time=window_start,
                        end_time=min(window_end, period_end),
                        tweet_fields=[
                            "created_at",
                            "author_id",
                            "source",
                            "in_reply_to_user_id",
                            "lang",
                            "public_metrics",
                        ],
                        expansions="author_id",
                        user_fields=[
                            "created_at",
                            "description",
                            "location",
                            "public_metrics",
                            "profile_image_url",
                        ],
                        max_results=500,
                        limit=page_limit,
                    )

                    for response in paginator:
                        users = {
                            user.id: user
                            for user in (response.includes or {}).get("users", [])
                        }
                        for tweet in response.data or []:
                            day_total += 1
                            record = tweet_record(
                                tweet, users[tweet.author_id], period_total + day_total
                            )
                            if tweets_writer is None:
                                tweets_writer = csv.DictWriter(
                                    tweets_file, fieldnames=record.keys()
                                )
                                tweets_writer.writeheader()
                            tweets_writer.writerow(record)

                    daily_writer.writerow(
                        [
                            format_timestamp(window_start),
                            format_timestamp(min(window_end, period_end)),
                            day_total,
                        ]
                    )
                    period_total += day_total
                    current_day += timedelta(days=1)

            period_writer.writerow(
                [format_timestamp(period_start), format_timestamp(period_end), period_total]
            )


def parse_arguments():
    """Define command-line inputs."""
    parser = argparse.ArgumentParser(
        description="Count or collect tweets. "
    )
    parser.add_argument(
        "mode",
        choices=["count", "collect"],
        help="Run the pre-collection count stage or the tweet collection stage.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Directory for generated tweet and count CSV files.",
    )
    parser.add_argument(
        "--query",
        default=DEFAULT_QUERY,
        help="Twitter API query; defaults to the query used in the study.",
    )
    parser.add_argument(
        "--counts",
        type=Path,
        help="Daily-count CSV from count mode; required in collect mode.",
    )
    parser.add_argument(
        "--threshold",
        type=int,
        default=6000,
        help="Daily volume threshold for full-day collection (default: 6000).",
    )
    parser.add_argument(
        "--page-limit",
        type=int,
        default=3,
        help="Maximum API pages retrieved per selected window (default: 3).",
    )
    return parser.parse_args()


def main():
    """Run the requested counting or collection stage."""
    args = parse_arguments()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    periods = [
        (parse_timestamp(period_start), parse_timestamp(period_end))
        for period_start, period_end in PERIOD_TIMESTAMPS
    ]
    client = create_client()

    if args.mode == "count":
        count_tweets(client, args.query, periods, args.output_dir)
        return

    if args.counts is None:
        raise ValueError("--counts is required in collect mode.")
    daily_counts = read_daily_counts(args.counts)
    collect_tweets(
        client,
        args.query,
        periods,
        daily_counts,
        args.output_dir,
        args.threshold,
        args.page_limit,
    )


if __name__ == "__main__":
    main()
